-- BANK-4: customer created date (used by the customers CSV export) and the export audit table.
-- This repository has no migration tool on the classpath (pom.xml has no Flyway/Liquibase and
-- spring.jpa.hibernate.ddl-auto=create-drop on H2), so Hibernate generates this schema at runtime.
-- The statements below are the equivalent Oracle DDL, for whoever applies this change to a real
-- Oracle schema.

ALTER TABLE customers ADD (created_at TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL);

CREATE TABLE data_exports (
    id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exported_by  VARCHAR2(255) NOT NULL,
    export_type  VARCHAR2(20)  NOT NULL,
    record_count NUMBER(19)    NOT NULL,
    exported_at  TIMESTAMP(6)  NOT NULL
);
