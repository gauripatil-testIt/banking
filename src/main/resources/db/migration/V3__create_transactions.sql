-- BANK-8: the transaction model behind the filtered transaction listing.
-- Like V1 and V2, this repository has no migration tool on the classpath (pom.xml has no
-- Flyway/Liquibase and spring.jpa.hibernate.ddl-auto=create-drop on H2), so Hibernate generates
-- the runtime schema from Transaction. The statements below are the equivalent Oracle DDL, for
-- whoever applies this change to a real Oracle schema.

CREATE TABLE transactions (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id NUMBER(19)    NOT NULL REFERENCES customers(id),
    type        VARCHAR2(16)  NOT NULL,
    status      VARCHAR2(16)  NOT NULL,
    amount      NUMBER(19,2)  NOT NULL,
    occurred_at TIMESTAMP(6)  NOT NULL
);