-- BANK-8: the outbox every background task is recorded in, drained to RabbitMQ by the scheduled
-- publisher. This repository has no migration tool on the classpath (pom.xml has no Flyway/Liquibase
-- and spring.jpa.hibernate.ddl-auto=create-drop on H2), so Hibernate generates this schema at runtime
-- from entity/BackgroundTaskOutboxEntry. The statements below are the equivalent Oracle DDL, for
-- whoever applies this change to a real Oracle schema.
--
-- The UNIQUE constraint on task_id is what mechanically keeps a duplicate submission of the same task
-- for the same record from being stored twice, and the CHECK constraint keeps status to the three
-- states the publisher knows.

CREATE TABLE background_task_outbox (
    id               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id          VARCHAR2(36)   NOT NULL,
    task_type        VARCHAR2(40)   NOT NULL,
    record_type      VARCHAR2(40)   NOT NULL,
    record_id        NUMBER(19)     NOT NULL,
    customer_id      NUMBER(19),
    requested_by     VARCHAR2(255)  NOT NULL,
    correlation_id   VARCHAR2(255)  NOT NULL,
    payload          CLOB           NOT NULL,
    status           VARCHAR2(20)   NOT NULL,
    attempts         NUMBER(10) DEFAULT 0 NOT NULL,
    next_attempt_at  TIMESTAMP(6)   NOT NULL,
    last_error       VARCHAR2(1000),
    published_at     TIMESTAMP(6),
    created_at       TIMESTAMP(6)   NOT NULL,
    CONSTRAINT uk_background_task_outbox_task_id UNIQUE (task_id),
    CONSTRAINT ck_background_task_outbox_status CHECK (status IN ('PENDING', 'PUBLISHED', 'FAILED'))
);

-- The drain query: due PENDING rows in id order.
CREATE INDEX ix_background_task_outbox_drain ON background_task_outbox (status, next_attempt_at, id);

-- Reading the rows of one task type, which is also what a reviewer inspects per queue.
CREATE INDEX ix_background_task_outbox_type ON background_task_outbox (task_type, id);
