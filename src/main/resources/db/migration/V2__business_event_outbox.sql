-- BANK-7: the transactional outbox every business event is recorded in, drained to Kafka by the
-- scheduled publisher. This repository has no migration tool on the classpath (pom.xml has no
-- Flyway/Liquibase and spring.jpa.hibernate.ddl-auto=create-drop on H2), so Hibernate generates
-- this schema at runtime from entity/BusinessEventOutboxEntry. The statements below are the
-- equivalent Oracle DDL, for whoever applies this change to a real Oracle schema.
--
-- The UNIQUE constraint on event_id is what mechanically keeps a retry from storing a second copy
-- of the same event, and the CHECK constraint keeps status to the three states the publisher knows.

CREATE TABLE business_event_outbox (
    id               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id         VARCHAR2(36)  NOT NULL,
    event_type       VARCHAR2(40)  NOT NULL,
    event_version    NUMBER(10)    NOT NULL,
    occurred_at      TIMESTAMP(6)  NOT NULL,
    customer_id      NUMBER(19),
    account_id       NUMBER(19),
    actor            VARCHAR2(255) NOT NULL,
    correlation_id   VARCHAR2(255) NOT NULL,
    business_key     VARCHAR2(64)  NOT NULL,
    payload          CLOB          NOT NULL,
    status           VARCHAR2(20)  NOT NULL,
    attempts         NUMBER(10) DEFAULT 0 NOT NULL,
    next_attempt_at  TIMESTAMP(6)  NOT NULL,
    last_error       VARCHAR2(1000),
    published_at     TIMESTAMP(6),
    dead_lettered_at TIMESTAMP(6),
    created_at       TIMESTAMP(6)  NOT NULL,
    CONSTRAINT uk_business_event_outbox_event_id UNIQUE (event_id),
    CONSTRAINT ck_business_event_outbox_status CHECK (status IN ('PENDING', 'PUBLISHED', 'FAILED'))
);

-- The drain query: due PENDING rows in id order.
CREATE INDEX ix_business_event_outbox_drain ON business_event_outbox (status, next_attempt_at, id);

-- Per-key ordering: the unresolved earlier rows of one business key.
CREATE INDEX ix_business_event_outbox_key ON business_event_outbox (business_key, id);
