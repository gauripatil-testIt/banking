-- BANK-9: the registry of the events a consumer has already handled, so a replay of a dead-lettered
-- item whose event already ran its effect is skipped instead of repeating it. This repository has no
-- migration tool on the classpath (pom.xml has no Flyway/Liquibase and
-- spring.jpa.hibernate.ddl-auto=create-drop on H2), so Hibernate generates this schema at runtime
-- from entity/ProcessedEvent. The statements below are the equivalent Oracle DDL, for whoever applies
-- this change to a real Oracle schema.
--
-- The UNIQUE constraint on event_id is what mechanically stops a second delivery of the same event –
-- a replay through the dead-letter API, or a concurrent duplicate the broker delivers – from
-- committing the same effect twice. The marker and the effect are written in one transaction, so a
-- handler that fails leaves no marker behind and the event is handled again on its next delivery.

CREATE TABLE processed_events (
    id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     VARCHAR2(36) NOT NULL,
    event_type   VARCHAR2(40) NOT NULL,
    processed_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_processed_events_event_id UNIQUE (event_id)
);
