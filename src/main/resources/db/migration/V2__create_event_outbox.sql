-- BANK-7: the durable transactional outbox for business events.
-- Every event from BANK-6 is written to this table in the same transaction as the business
-- change it announces, and a scheduled relay drains the PENDING rows to Kafka. A row is only
-- deleted once the broker has acknowledged it, so an outage delays events instead of losing them.
--
-- Like V1, this repository has no migration tool on the classpath (pom.xml has no Flyway/Liquibase
-- and spring.jpa.hibernate.ddl-auto=create-drop on H2), so Hibernate generates the runtime schema
-- from OutboxEvent. The statements below are the equivalent Oracle DDL, for whoever applies this
-- change to a real Oracle schema.

CREATE TABLE event_outbox (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        VARCHAR2(36)   NOT NULL UNIQUE,
    event_type      VARCHAR2(64)   NOT NULL,
    event_version   NUMBER(10)     NOT NULL,
    subject_type    VARCHAR2(16)   NOT NULL,
    subject_id      NUMBER(19)     NOT NULL,
    sequence_no     NUMBER(19)     NOT NULL,
    ordering_key    VARCHAR2(64)   NOT NULL,
    topic           VARCHAR2(255)  NOT NULL,
    payload         CLOB           NOT NULL,
    status          VARCHAR2(16)   NOT NULL,
    attempt_count   NUMBER(10)     DEFAULT 0 NOT NULL,
    failure_reason  VARCHAR2(1000) NULL,
    created_at      TIMESTAMP(6)   NOT NULL,
    next_attempt_at TIMESTAMP(6)   NOT NULL,
    published_at    TIMESTAMP(6)   NULL,
    CONSTRAINT uq_event_outbox_subject_seq UNIQUE (subject_type, subject_id, sequence_no)
);

-- The relay's work queue: due PENDING rows, oldest first. FAILED rows stay in the table for
-- investigation (event id plus reason) and must never be picked up by this access path.
CREATE INDEX idx_event_outbox_status_due ON event_outbox (status, next_attempt_at, id);
