-- BANK-8: the task outbox for background work (welcome email, statement generation,
-- document export, document scan).
-- This repository has no migration tool on the classpath (pom.xml has no Flyway/Liquibase and
-- spring.jpa.hibernate.ddl-auto=create-drop on H2), so Hibernate generates this schema at runtime
-- from BackgroundTask. The statements below are the equivalent Oracle DDL, for whoever applies this
-- change to a real Oracle schema -- the same convention as V1.
--
-- The unique constraint, not application code, is what makes a repeated submission of the same task
-- insert nothing: business_key is the business identity of the work (e.g. the document id for a
-- scan), so two concurrent submissions cannot both create a row.

CREATE TABLE background_tasks (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_type       VARCHAR2(40)  NOT NULL,
    business_key    VARCHAR2(255) NOT NULL,
    status          VARCHAR2(20)  NOT NULL,
    event_id        VARCHAR2(36)  NOT NULL,
    correlation_id  VARCHAR2(255) NOT NULL,
    requested_by    VARCHAR2(255) NOT NULL,
    message_json    CLOB          NOT NULL,
    attempts        NUMBER(10)    NOT NULL,
    next_attempt_at TIMESTAMP(6),
    published_at    TIMESTAMP(6),
    created_at      TIMESTAMP(6)  NOT NULL,
    CONSTRAINT uq_background_tasks_task_key UNIQUE (task_type, business_key)
);
