-- BANK-9: dead-lettered items get a real database home, and the outbox row remembers when it
-- first and last failed. This repository has no migration tool on the classpath (pom.xml has no
-- Flyway/Liquibase and spring.jpa.hibernate.ddl-auto=create-drop on H2), so Hibernate generates
-- this schema at runtime from entity/DeadLetterEntry and entity/BusinessEventOutboxEntry. The
-- statements below are the equivalent Oracle DDL, for whoever applies this change to a real
-- Oracle schema.
--
-- The UNIQUE constraint on (source, source_id) is what mechanically keeps a repeated exhaustion
-- of the same item from being stored twice, and the CHECK constraint keeps a dead-lettered item
-- to the two states operations know: waiting to be replayed, and replayed.

ALTER TABLE business_event_outbox ADD (
    first_failed_at TIMESTAMP(6),
    last_failed_at  TIMESTAMP(6)
);

CREATE TABLE dead_letter_items (
    id               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source           VARCHAR2(120)  NOT NULL,
    source_id        VARCHAR2(36)   NOT NULL,
    event_type       VARCHAR2(40)   NOT NULL,
    payload          CLOB           NOT NULL,
    reason           VARCHAR2(1000),
    attempts         NUMBER(10)     NOT NULL,
    first_failed_at  TIMESTAMP(6)   NOT NULL,
    last_failed_at   TIMESTAMP(6)   NOT NULL,
    dead_lettered_at TIMESTAMP(6)   NOT NULL,
    status           VARCHAR2(20)   NOT NULL,
    replay_count     NUMBER(10) DEFAULT 0 NOT NULL,
    replayed_by      VARCHAR2(255),
    replayed_at      TIMESTAMP(6),
    CONSTRAINT uk_dead_letter_items_source UNIQUE (source, source_id),
    CONSTRAINT ck_dead_letter_items_status CHECK (status IN ('PENDING', 'REPLAYED'))
);

-- Operations review the items still waiting to be replayed, oldest first.
CREATE INDEX ix_dead_letter_items_status ON dead_letter_items (status, id);
